    lines = [
        "# ImageNet commands require HuggingFace ImageNet access plus train/val label tensors.",
        "# Generate labels with: python src/dataio/imagenet.py",
    ]
    for seed in args.seeds:
        save_dir = Path(args.runs) / "imagenet_resnet18" / f"seed_{seed}"
        cmd = [
            "python",
            "-u",
            "main.py",
            "unlearn",
            "--dataset",
            "imagenet",
            "--imagenet_arch",
            "--arch",
            "resnet18",
            "--save_dir",
            str(save_dir),
            "--mask",
            str(save_dir / "0model_SA_best.pth.tar"),
            "--class_to_replace",
            "0",
            "--unlearn",
            "FT",
            "--unlearn_epochs",
            "5",
            "--unlearn_lr",
            "0.001",
            "--batch_size",
            "1024",
            "--input_size",
            "224",
            "--train_y_file",
            "./labels/train_ys.pth",
            "--val_y_file",
            "./labels/val_ys.pth",
            "--seed",
            str(seed),
        ]
        lines.append(shell_join(cmd))
    lines.append("")
